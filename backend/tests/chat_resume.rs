//! Approved seams S2 HTTP and S3 real CLI boundary; no internal matching mocks.
mod common;
use std::{path::Path, sync::Arc};
use common::{HerdrFixture, TempDir, TestServer, post_json_over_tcp};
use herdr_bot::{PowerOff, PowerOffFailure};
use serde_json::{Value, json};
struct NeverPowerOff;
impl PowerOff for NeverPowerOff {
    fn power_off(&self) -> Result<(), PowerOffFailure> { panic!("resume must not power off") }
}
fn config(root: &TempDir, herdr: &HerdrFixture) -> herdr_bot::Config {
    let mut config = common::config(Path::new("unused.bat"), root.path());
    config.sessions.history_file = root.path().join("history.json");
    config.herdr.executable = herdr.executable().to_owned();
    config
}
fn history(config: &herdr_bot::Config, kind: &str, id: &str, file: Option<&Path>) {
    std::fs::write(&config.sessions.history_file, json!([{
        "sessionId":id,"sessionName":"Same name","agentType":kind,"cwd":"C:/same cwd",
        "firstRecordedAt":123,"sessionFile":file.map(|p| p.to_str().unwrap())
    }]).to_string()).unwrap();
}
fn agent(kind: &str, reference_kind: &str, value: &str, workspace: &str, tab: &str, pane: &str) -> Value {
    json!({"agent":kind,"name":"same-name","cwd":"C:/same cwd","agent_status":"working",
        "workspace_id":workspace,"tab_id":tab,"pane_id":pane,"focused":false,
        "agent_session":{"agent":kind,"source":format!("herdr:{kind}"),"kind":reference_kind,"value":value}})
}
// P2: literal ID equality/inequality and a saved path versus a returned ID.
// The OMP title prefix is independently prewritten, never generated by the SUT.
#[tokio::test]
async fn identity_expressions_match_only_the_same_native_conversation() {
    for (saved_as_path, candidate, expected) in [(false,"native-one","located"), (false,"different-native","failed"), (true,"native-one","located"), (true,"different-native","failed")] {
        let root = TempDir::new("resume-expressions");
        let herdr = HerdrFixture::new("resume-expressions");
        let config = config(&root, &herdr);
        let native = root.path().join("omp.jsonl");
        std::fs::write(&native, "{\"type\":\"title\",\"title\":\"Same name\"}\n{\"type\":\"session\",\"id\":\"native-one\",\"cwd\":\"C:/same cwd\"}\n").unwrap();
        let selected = if saved_as_path { native.to_str().unwrap() } else { "native-one" };
        history(&config, "omp", selected, Some(&native));
        let mut target = agent("omp", "id", candidate, "w2", "w2:t8", "w2:p3");
        target["agent_status"] = json!("done");
        herdr.set_behavior(json!({"agents":[target],"fail_workspace_list":true}));
        let server = TestServer::start_app(herdr_bot::app_with_power_off(&config, Arc::new(NeverPowerOff))).await;
        let reply = resume(&server, selected).await;
        assert_eq!(reply.status, if expected == "located" { 200 } else { 502 }, "{}", reply.body);
        let body: Value = serde_json::from_str(&reply.body).unwrap();
        assert_eq!(body["outcome"], expected);
        // A different identity reaches cwd fallback, not the decoy's focus.
        // Refusing workspace evidence must remain a failure, not success.
        if expected == "failed" { assert_eq!(body["code"], "herdr-command-failed"); }
        assert!(herdr.calls().iter().all(|call| matches!(call["kind"].as_str().unwrap(), "agent_list" | "agent_focus" | "agent_get" | "workspace_list")));
        assert!(herdr.tabs().is_empty());
    }
}

async fn resume(server: &TestServer, id: &str) -> common::HttpResponse {
    post_json_over_tcp(server.addr(), "/api/chats/resume", &json!({"sessionId":id}).to_string()).await
}
// P20/P22: neither transport/parse failure nor a refused/unconfirmed focus is
// an empty query or success. Observe the full constrained command inventory.
#[tokio::test]
async fn query_and_focus_failures_never_report_success_or_start_copies() {
    for (fault,stage,code) in [
        ("unavailable","lookup","herdr-unavailable"),
        ("fail_agent_list","lookup","herdr-command-failed"),
        ("invalid_agent_list","lookup","herdr-unexpected-response"),
        ("fail_agent_focus","focus","herdr-command-failed"),
        ("unconfirmed_focus","focus","herdr-unexpected-response"),
    ] {
        let root = TempDir::new("resume-failures");
        let herdr = HerdrFixture::new("resume-failures");
        let mut config = config(&root,&herdr);
        history(&config,"pi","native-one",None);
        let mut behavior = json!({"agents":[agent("pi","id","native-one","w1","w1:t1","w1:p1")]});
        behavior[fault] = json!(true);
        herdr.set_behavior(behavior);
        if fault == "unavailable" { config.herdr.executable = root.path().join("does-not-exist.exe"); }
        let server = TestServer::start_app(herdr_bot::app_with_power_off(&config,Arc::new(NeverPowerOff))).await;
        let reply = resume(&server,"native-one").await;
        assert_eq!(reply.status,502,"{fault}: {}",reply.body);
        let body: Value = serde_json::from_str(&reply.body).unwrap();
        assert_eq!(body["outcome"],"failed");
        assert_eq!(body["stage"],stage);
        assert_eq!(body["code"],code);
        assert!(body["message"].as_str().unwrap().contains("尚未恢复"));
        let calls = herdr.calls();
        assert!(calls.iter().all(|c| matches!(c["kind"].as_str().unwrap(),"agent_list" | "agent_focus" | "agent_get")));
        if stage == "lookup" { assert!(calls.iter().all(|c| c["kind"] == "agent_list")); }
        assert!(herdr.tabs().is_empty());
    }
}

// P23: an independent HTTP caller cannot override any execution authority.
// A genuine target exists so silently accepting an override would be observable.
#[tokio::test]
async fn client_can_only_select_history_not_supply_execution_content() {
    let root = TempDir::new("resume-client-authority");
    let herdr = HerdrFixture::new("resume-client-authority");
    let config = config(&root,&herdr);
    history(&config,"pi","native-one",None);
    herdr.set_behavior(json!({"agents":[agent("pi","id","native-one","w1","w1:t1","w1:p1")]}));
    let server = TestServer::start_app(herdr_bot::app_with_power_off(&config,Arc::new(NeverPowerOff))).await;
    for (field,value) in [
        ("sourceTaskId",json!("attacker-source")), ("taskId",json!("attacker-current-task")),
        ("extensions",json!(["C:/evil-extension.ts"])), ("entrypoint",json!("C:/evil-extension.ts")),
        ("envConfig",json!({"extensions":["attacker-extension"]})),
        ("executable",json!("evil.exe")), ("command",json!("Write-Output injected")),
        ("args",json!(["--eval","evil"])), ("sessionFile",json!("C:/evil.jsonl")),
        ("nativeId",json!("different")), ("input",json!("injected prompt")), ("cwd",json!("C:/evil")),
    ] {
        let mut body = json!({"sessionId":"native-one"});
        body[field] = value;
        let reply = post_json_over_tcp(server.addr(),"/api/chats/resume",&body.to_string()).await;
        assert_eq!(reply.status,422,"field {field}: {}",reply.body);
    }
    assert!(herdr.calls().is_empty());
    assert!(herdr.tabs().is_empty());
    assert_eq!(resume(&server,"native-one").await.status,200);
    assert_eq!(herdr.calls()[1]["argv"],json!(["agent","focus","w1:p1"]));
}

// P5: prewritten ordering expectation, deliberately different enumeration orders.
// Every attempt must query anew and choose the same actual location.
#[tokio::test]
async fn multiple_matches_use_stable_location_order_on_every_attempt() {
    let root = TempDir::new("resume-stable");
    let herdr = HerdrFixture::new("resume-stable");
    let config = config(&root,&herdr);
    history(&config,"omp","native-one",None);
    let server = TestServer::start_app(herdr_bot::app_with_power_off(&config,Arc::new(NeverPowerOff))).await;
    let a = agent("omp","id","native-one","w1","w1:t3","w1:p7");
    let b = agent("omp","id","native-one","w9","w9:t1","w9:p1");
    for agents in [json!([b.clone(),a.clone()]),json!([a,b])] {
        herdr.set_behavior(json!({"agents":agents}));
        let reply = resume(&server,"native-one").await;
        assert_eq!(reply.status,200,"{}",reply.body);
        let body: Value = serde_json::from_str(&reply.body).unwrap();
        assert_eq!(body["matchCount"],2);
        assert_eq!(body["target"]["paneId"],"w1:p7");
    }
    let calls = herdr.calls();
    assert_eq!(calls.iter().filter(|c| c["kind"] == "agent_list").count(),2);
    assert_eq!(calls.iter().filter(|c| c["kind"] == "agent_focus").count(),2);
    assert!(calls.iter().all(|c| matches!(c["kind"].as_str().unwrap(),"agent_list" | "agent_focus" | "agent_get")));
}

// A broken candidate must not hide valid matches, regardless of enumeration
// order. Valid duplicates still use the existing stable navigation order.
#[tokio::test]
async fn invalid_candidate_identity_is_skipped_without_hiding_valid_matches() {
    for kind in ["pi", "omp"] {
        for fault in ["missing-file", "invalid-header", "missing-reference", "wrong-source", "empty-value", "unknown-kind", "relative-path"] {
            let root = TempDir::new("resume-invalid-candidate");
            let herdr = HerdrFixture::new("resume-invalid-candidate");
            let config = config(&root, &herdr);
            history(&config, kind, "native-one", None);
            let path = root.path().join("broken.jsonl");
            if fault == "invalid-header" { std::fs::write(&path, "not JSON\n").unwrap(); }
            let mut broken = agent(kind, "path", path.to_str().unwrap(), "w0", "w0:t1", "w0:p1");
            match fault {
                "missing-reference" => broken["agent_session"] = Value::Null,
                "wrong-source" => broken["agent_session"]["source"] = json!("untrusted"),
                "empty-value" => broken["agent_session"]["value"] = json!(" "),
                "unknown-kind" => broken["agent_session"]["kind"] = json!("unknown"),
                "relative-path" => broken["agent_session"]["value"] = json!("relative.jsonl"),
                _ => {}
            }
            let first = agent(kind, "id", "native-one", "w1", "w1:t1", "w1:p1");
            let second = agent(kind, "id", "native-one", "w2", "w2:t1", "w2:p1");
            let server = TestServer::start_app(herdr_bot::app_with_power_off(&config, Arc::new(NeverPowerOff))).await;
            for entries in [json!([broken.clone(), second.clone(), first.clone()]), json!([second, first, broken])] {
                herdr.set_behavior(json!({"agents":entries}));
                let reply = resume(&server, "native-one").await;
                assert_eq!(reply.status, 200, "{kind}/{fault}: {}", reply.body);
                let body: Value = serde_json::from_str(&reply.body).unwrap();
                assert_eq!(body["outcome"], "located");
                assert_eq!(body["target"]["paneId"], "w1:p1");
                assert_eq!(body["matchCount"], 2);
                assert!(body.get("degradations").is_none());
            }
            assert!(herdr.calls().iter().all(|c| matches!(c["kind"].as_str().unwrap(), "agent_list" | "agent_focus" | "agent_get")));
            assert!(herdr.tabs().is_empty());
        }
    }
}

