"""S1 file seam: validate independent literals against the published JSON Schema.

This verifies representations, not HTTP acceptance or Rust business execution.
Expected values are approved contract examples, never generated by a producer.
Run with Python 3.11+ and scripts/requirements-contracts.txt installed.
"""
import json
from pathlib import Path
import unittest

from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parents[1] / "docs" / "contracts"


class ScriptContracts(unittest.TestCase):
    def test_public_literals(self):
        # A plausible violation is treating an arbitrary capability as runnable.
        # Literal unknown/mixed targets must fail, both fixed identifiers pass.
        schema = json.loads((ROOT / "rust-script-bots.schema.json").read_text(encoding="utf-8"))
        Draft202012Validator.check_schema(schema)
        cases = [json.loads(line) for line in (ROOT / "rust-script-bots.examples.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
        self.assertTrue(cases)
        for case in cases:
            with self.subTest(case=case["id"]):
                self.assertTrue(case["definition"] in schema["$defs"], f"Missing public representation: {case['definition']}")
                validator = Draft202012Validator({"$ref": f"#/$defs/{case['definition']}", "$defs": schema["$defs"]})
                errors = list(validator.iter_errors(case["value"]))
                self.assertEqual(not errors, case["valid"], "\n".join(error.message for error in errors))


if __name__ == "__main__":
    unittest.main()
