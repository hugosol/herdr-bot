// Approved S1/S2 P01/P02. Source: normal Task and exact Map filename are
// alternative targets. A JSON-only addition cannot pass the form/reload check.
test('P01 task and Map targets save through forms and reload without dual-binding overwrite', async ({ page }) => {
  server = await startServer({ separateCwd: true, herdr: {} })
  const taskResponse = await page.request.post(`${server.baseURL}/api/tasks`, { data: { name: 'Literal worker', taskType: 'normal', agent: 'omp', chatName: '{chat.id}', model: 'default', thinking: 'default', skill: null, prompt: 'WORKER' } })
  expect(taskResponse.ok()).toBe(true)
  const task = (await taskResponse.json()).tasks.find((item: { name: string }) => item.name === 'Literal worker')
  const maps = path.join(server.cwd, 'meta-data/workflow-maps')
  fs.mkdirSync(maps, { recursive: true })
  fs.writeFileSync(path.join(maps, 'literal-child.json'), JSON.stringify({ title: 'Literal child', description: '', nodes: {} }))
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-bot').click()
  await page.getByRole('button', { name: 'new', exact: true }).click()
  await page.getByLabel('Bot ID', { exact: true }).fill('literal-capability')
  await page.getByLabel('Bot 内容 JSON', { exact: true }).fill(JSON.stringify({ name: 'Literal capability', when: '', plan_guide: '', node_guide: '' }))
  await page.getByRole('combobox', { name: 'Task', exact: true }).selectOption(`task:${task.id}`)
  await page.getByRole('button', { name: 'save', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Bot 预览', exact: true })).toContainText('Literal worker')
  await page.reload()
  await page.getByTestId('tab-bot').click()
  await page.getByRole('button', { name: 'Literal capability · literal-capability', exact: true }).click()
  await page.getByRole('button', { name: 'edit', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Task', exact: true })).toHaveValue(`task:${task.id}`)
  await page.getByRole('combobox', { name: 'Map', exact: true }).selectOption('literal-child.json')
  expect(JSON.parse(await page.getByLabel('Bot 内容 JSON', { exact: true }).inputValue())).toEqual({ name: 'Literal capability', when: '', plan_guide: '', node_guide: '', map_file: 'literal-child.json' })
  await page.getByRole('button', { name: 'save', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Bot 预览', exact: true })).toContainText('literal-child.json')
  await page.reload()
  await page.getByTestId('tab-bot').click()
  await page.getByRole('button', { name: 'Literal capability · literal-capability', exact: true }).click()
  await page.getByRole('button', { name: 'edit', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Map', exact: true })).toHaveValue('literal-child.json')
  const edit = await (await page.request.post(`${server.baseURL}/api/scheduler/bots/edit`, { data: { id: 'literal-capability' } })).json()
  const dual = JSON.stringify({ ...edit.content, task_id: task.id })
  await page.getByLabel('Bot 内容 JSON', { exact: true }).fill(dual)
  await page.getByRole('button', { name: 'save', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('互斥')
  await expect(page.getByLabel('Bot 内容 JSON', { exact: true })).toHaveValue(dual)
  expect(await (await page.request.post(`${server.baseURL}/api/scheduler/bots/edit`, { data: { id: 'literal-capability' } })).json()).toEqual(edit)
  expect(server.herdrCalls()).toEqual([])
})
