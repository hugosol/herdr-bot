import fs from 'node:fs'
import path from 'node:path'
import { expect, test } from '@playwright/test'
import { startServer, type E2EServer } from './support'
import { showMapDirectory } from './ui'

// S1/S2 P37 and node manager shape: form writes node-local manager only;
// cancelling or refusing Map deletion leaves both definitions byte-preserved.
test('Map node manager is editable and referenced Map deletion is refused without unbinding', async ({ page }) => {
  server = await startServer({ separateCwd: true, herdr: {} })
  const response = await page.request.post(`${server.baseURL}/api/tasks`, { data: { name: 'Literal manager', taskType: 'manager', agent: 'omp', chatName: '{chat.id}', model: 'default', thinking: 'default', skill: null, prompt: 'MANAGER' } })
  expect(response.ok()).toBe(true)
  const manager = (await response.json()).tasks.find((item: { name: string }) => item.name === 'Literal manager')
  const maps = path.join(server.cwd, 'meta-data/workflow-maps'), bots = path.join(server.cwd, 'meta-data/bots')
  fs.mkdirSync(maps, { recursive: true }); fs.mkdirSync(bots, { recursive: true })
  const target = JSON.stringify({ title: 'Child target', description: '', nodes: {} })
  const capability = JSON.stringify({ id: 'nested', name: 'Nested', when: '', plan_guide: '', node_guide: '', map_file: 'child.json' })
  fs.writeFileSync(path.join(maps, 'child.json'), target)
  fs.writeFileSync(path.join(bots, 'nested.json'), capability)
  fs.writeFileSync(path.join(maps, 'parent.json'), JSON.stringify({ title: 'Parent', description: '', nodes: { call: { title: 'Call child', bot_id: 'nested', input: 'literal input', zone: 'node-zone', blocked_by: [] } } }))
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-scheduler').click()
  await page.getByRole('button', { name: 'Parent', exact: true }).click()
  await page.getByRole('region', { name: '节点列表', exact: true }).getByRole('button', { name: 'Call child call', exact: true }).click()
  await page.getByRole('button', { name: '修改 node', exact: true }).click()
  await page.getByRole('combobox', { name: 'manager Task', exact: true }).selectOption(manager.id)
  await page.getByRole('button', { name: '保存 node', exact: true }).click()
  const read = await page.request.get(`${server.baseURL}/api/scheduler/maps/parent.json`)
  expect((await read.json()).nodes.call.manager_task_id).toBe(manager.id)
  await page.reload()
  await page.getByTestId('tab-scheduler').click()
  await page.getByRole('button', { name: 'Parent', exact: true }).click()
  await page.getByRole('region', { name: '节点列表', exact: true }).getByRole('button', { name: 'Call child call', exact: true }).click()
  await expect(page.getByRole('region', { name: 'node 详情', exact: true })).toContainText(manager.id)
  expect(fs.readFileSync(path.join(bots, 'nested.json'), 'utf8')).toBe(capability)
  await showMapDirectory(page)
  await page.getByRole('button', { name: 'Child target', exact: true }).click()
  await page.getByRole('button', { name: '删除 Map', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  expect(fs.readFileSync(path.join(maps, 'child.json'), 'utf8')).toBe(target)
  await page.getByRole('button', { name: '删除 Map', exact: true }).click()
  await page.getByRole('button', { name: '保留历史', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('nested')
  expect(fs.readFileSync(path.join(maps, 'child.json'), 'utf8')).toBe(target)
  expect(fs.readFileSync(path.join(bots, 'nested.json'), 'utf8')).toBe(capability)
  expect(server.herdrCalls()).toEqual([])
})

let server: E2EServer | null = null
