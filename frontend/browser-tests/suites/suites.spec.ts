// Approved seams S1/S2/S3. P3's independent declaration below must be the
// actual authority, not a UI-only copy. A save that updates only memory (or a
// generated manifest) would disagree with both the disk literal and read-back.
test('P3 manages an unreferenced Suite through the main interface and authoritative file', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const definitions = path.join(path.dirname(server.configPath), 'meta-data', 'suites.json')
  const mcp = path.join(path.dirname(server.configPath), 'meta-data', 'mcp.json')
  fs.mkdirSync(path.dirname(mcp), { recursive: true })
  const catalogBytes = '{"mcpServers":{"catalog-search":{"command":"controlled-search","args":["--stdio"]}}}\n'
  fs.writeFileSync(mcp, catalogBytes)
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  const list = page.getByRole('region', { name: 'Suite 列表', exact: true })
  await expect(list).toContainText('尚未定义 Suite')
  const fixed = page.getByRole('region', { name: '全局固定扩展', exact: true })
  await expect(fixed).toBeVisible()
  await expect(fixed.getByRole('checkbox')).toHaveCount(0)
  const catalog = await (await page.request.get(`${server.baseURL}/api/suites`)).json()
  expect(catalog.fixedExtensions).toEqual(expect.arrayContaining([
    expect.objectContaining({ id: 'omp-connect-bot', kind: 'fixed', roles: ['standalone', 'manager', 'node', 'chief', 'chief-delegated'] }),
    expect.objectContaining({ id: 'pi-connect-bot', kind: 'fixed', roles: ['standalone', 'manager', 'node', 'chief', 'chief-delegated'] }),
  ]))
  for (const extension of catalog.fixedExtensions as { id: string; label: string; agent: string; entrypoint: string; roles: ('standalone' | 'manager' | 'node' | 'chief' | 'chief-delegated')[] }[]) {
    const group = fixed.getByRole('region', { name: `${extension.agent.toUpperCase()} 固定扩展`, exact: true })
    const row = group.getByRole('listitem').filter({ hasText: extension.id })
    await expect(row).toContainText(extension.label)
    await expect(row).toContainText(extension.entrypoint)
    await expect(row).toContainText(`适用：${extension.roles.map(role => ({ standalone: '普通独立Chat', manager: '管理者', node: 'workflow节点', chief: '需求分流者', 'chief-delegated': 'chief委派独立Chat' })[role]).join('、')}`)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await fixed.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: '创建 Suite', exact: true }).click()
  await expect(fixed).toBeVisible()
  expect(Object.keys(catalog).sort()).toEqual(['fixedExtensions', 'mcp', 'suites'])
  await expect(page.getByRole('group', { name: 'OMP 共享可选扩展', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /connect-bot/ })).toHaveCount(0)
  await page.getByLabel('Suite ID', { exact: true }).fill('review-tools')
  await page.getByLabel('Suite 名称', { exact: true }).fill('评审工具')
  await page.getByLabel('OMP 技能集合目录（每行一个路径）', { exact: true }).fill('${roots.skills}/review-collection\n../shared/research')
  await page.getByLabel('OMP Extensions（每行一个具体路径）', { exact: true }).fill('${roots.toolkit}/extensions/review')
  await page.getByLabel('Prompt templates（每行一个路径）', { exact: true }).fill('../prompts/review.md')
  await page.getByLabel('LSP 声明（JSON）', { exact: true }).fill('{"rust":{"command":"rust-analyzer","fileTypes":["rs"]}}')
  await page.getByLabel('catalog-search', { exact: true }).check()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  const expected = { id: 'review-tools', name: '评审工具', agents: ['omp'], skills: { omp: ['${roots.skills}/review-collection', '../shared/research'] }, extensions: { omp: ['${roots.toolkit}/extensions/review'] }, prompts: ['../prompts/review.md'], lsp: { rust: { command: 'rust-analyzer', fileTypes: ['rs'] } }, mcp: ['catalog-search'] }
  await expect(list.getByRole('button', { name: '评审工具 · review-tools', exact: true })).toBeVisible()
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toMatchObject({ suites: [expected] })
  expect(fs.readFileSync(mcp, 'utf8')).toBe(catalogBytes)
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await list.getByRole('button', { name: '评审工具 · review-tools', exact: true }).click()
  await expect(page.getByLabel('Suite ID', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('OMP 技能集合目录（每行一个路径）', { exact: true })).toHaveValue('${roots.skills}/review-collection\n../shared/research')
  await expect(page.getByLabel('catalog-search', { exact: true })).toBeChecked()
  await page.getByLabel('Suite 名称', { exact: true }).fill('更新后的评审工具')
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(list.getByRole('button', { name: '更新后的评审工具 · review-tools', exact: true })).toBeVisible()
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toMatchObject({ suites: [{ ...expected, name: '更新后的评审工具' }] })
  const response = await page.request.get(`${server.baseURL}/api/suites/review-tools`)
  expect(response.status()).toBe(200)
  expect(await response.json()).toMatchObject({ suite: { ...expected, name: '更新后的评审工具' } })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除 Suite', exact: true }).click()
  await expect(list).toContainText('尚未定义 Suite')
  await expect(fixed.getByRole('listitem')).toHaveCount(catalog.fixedExtensions.length)
  await expect(fixed.getByRole('checkbox')).toHaveCount(0)
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [] })
  expect(fs.readFileSync(mcp, 'utf8')).toBe(catalogBytes)
})

// P4: independent external bytes at an explicitly configured authority must win
// over default/cwd/generated lookalikes both before and after a real restart.
// A cached UI/database or a writer using cwd would fail the changed name/path.
test('P4 re-reads and restarts from the same externally maintained Suite authority', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const configDirectory = path.dirname(server.configPath)
  const authority = path.join(configDirectory, 'shared definitions with spaces')
  fs.mkdirSync(authority)
  const definitions = path.join(authority, 'user-suites.json')
  const external = '{"suites":[{"id":"external-tools","name":"外部独立定义","agents":["omp"],"skills":{"omp":["../skills/independent"]},"extensions":{},"prompts":[],"lsp":{},"mcp":[]}]}'
  fs.writeFileSync(definitions, external)
  const shadows = [path.join(server.cwd, 'meta-data'), path.join(configDirectory, 'meta-data'), path.join(configDirectory, 'generated')]
  for (const directory of shadows) {
    fs.mkdirSync(directory, { recursive: true })
    fs.writeFileSync(path.join(directory, 'suites.json'), '{"suites":[]}\n')
  }
  fs.appendFileSync(path.join(configDirectory, 'paths.toml'), `authority = '${authority}'\n`)
  fs.appendFileSync(server.configPath, "\n[suites]\ndefinition_file = '${roots.authority}/user-suites.json'\nmcp_file = 'shared definitions with spaces/central-mcp.json'\n")
  await server.restart()
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  await page.getByRole('button', { name: '外部独立定义 · external-tools', exact: true }).click()
  await expect(page.getByLabel('OMP 技能集合目录（每行一个路径）', { exact: true })).toHaveValue('../skills/independent')
  expect(fs.readFileSync(definitions, 'utf8')).toBe(external)
  const revised = '{"suites":[{"id":"external-tools","name":"手工修改后的定义","agents":["omp"],"skills":{"omp":["../skills/changed"]},"extensions":{},"prompts":["../prompts/manual.md"],"lsp":{},"mcp":[]}]}'
  fs.writeFileSync(definitions, revised)
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(page.getByLabel('Suite 名称', { exact: true })).toHaveValue('手工修改后的定义')
  await expect(page.getByLabel('Prompt templates（每行一个路径）', { exact: true })).toHaveValue('../prompts/manual.md')
  const response = await page.request.get(`${server.baseURL}/api/suites/external-tools`)
  expect(response.status()).toBe(200)
  expect(await response.json()).toMatchObject({ suite: { id: 'external-tools', name: '手工修改后的定义', agents: ['omp'], skills: { omp: ['../skills/changed'] }, extensions: {}, prompts: ['../prompts/manual.md'], lsp: {}, mcp: [] } })
  await server.restart()
  await page.reload()
  await page.getByTestId('tab-suite').click()
  await page.getByRole('button', { name: '手工修改后的定义 · external-tools', exact: true }).click()
  await expect(page.getByLabel('OMP 技能集合目录（每行一个路径）', { exact: true })).toHaveValue('../skills/changed')
  expect(fs.readFileSync(definitions, 'utf8')).toBe(revised)
  await page.getByLabel('Suite 名称', { exact: true }).fill('界面写回同一权威文件')
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toMatchObject({ suites: [{ id: 'external-tools', name: '界面写回同一权威文件', agents: ['omp'], skills: { omp: ['../skills/changed'] }, extensions: {}, prompts: ['../prompts/manual.md'], lsp: {}, mcp: [] }] })
  for (const directory of shadows) expect(fs.readFileSync(path.join(directory, 'suites.json'), 'utf8')).toBe('{"suites":[]}\n')
  expect(fs.readdirSync(authority)).toEqual(['user-suites.json'])
})

test('extension paths save multiple source entries independently, re-read authority, and filter disabled hosts', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const definitions = path.join(path.dirname(server.configPath), 'meta-data', 'suites.json')
  const firstPi = ['${roots.browser_extensions}/shared.ts', '../source packages/pi-entry.ts']
  const secondPi = ['../second source/pi-entry.ts']
  const omp = ['../omp native package', '../omp source/entry.ts']
  const suites = [
    { id: 'first', name: 'first', agents: ['omp', 'pi'], skills: {}, extensions: { omp, pi: firstPi }, prompts: [], lsp: {}, mcp: [], pi: { codemode: 'on' } },
    { id: 'second', name: 'second', agents: ['pi'], skills: {}, extensions: { pi: secondPi }, prompts: [], lsp: {}, mcp: [], pi: { codemode: 'on' } },
  ]
  fs.mkdirSync(path.dirname(definitions), { recursive: true })
  fs.writeFileSync(definitions, JSON.stringify({ suites }))
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  const piPaths = page.getByLabel('PI Extensions（每行一个具体路径）', { exact: true })
  const ompPaths = page.getByLabel('OMP Extensions（每行一个具体路径）', { exact: true })
  const persisted = () => JSON.parse(fs.readFileSync(definitions, 'utf8')).suites
  const save = async () => {
    await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  }
  await page.getByRole('button', { name: 'first · first', exact: true }).click()
  await expect(piPaths).toHaveValue(firstPi.join('\n'))
  await expect(ompPaths).toHaveValue(omp.join('\n'))
  await expect(page.getByRole('region', { name: '资源路径', exact: true }).getByRole('checkbox')).toHaveCount(0)
  const revisedPi = [...firstPi, '../extra source/non-index.ts']
  await piPaths.fill('  ' + revisedPi.join('\r\n') + '\n\n' + firstPi[0] + '\n')
  await save()
  expect(persisted()[0].extensions).toEqual({ omp, pi: revisedPi })
  expect(persisted()[1]).toMatchObject(suites[1])
  await expect(piPaths).toHaveValue(revisedPi.join('\n'))
  await page.getByRole('button', { name: 'second · second', exact: true }).click()
  await expect(piPaths).toHaveValue(secondPi.join('\n'))
  await expect(ompPaths).toHaveCount(0)
  await page.getByRole('button', { name: 'first · first', exact: true }).click()
  await expect(piPaths).toHaveValue(revisedPi.join('\n'))
  const manualPi = ['../manually maintained/first.ts', '../manually maintained/second.ts']
  const externallyEdited = persisted()
  externallyEdited[0].extensions.pi = manualPi
  fs.writeFileSync(definitions, JSON.stringify({ suites: externallyEdited }))
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(piPaths).toHaveValue(manualPi.join('\n'))
  await expect(ompPaths).toHaveValue(omp.join('\n'))
  await page.setViewportSize({ width: 390, height: 844 })
  await piPaths.focus()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByLabel('PI', { exact: true }).uncheck()
  await expect(piPaths).toHaveCount(0)
  await save()
  expect(persisted()[0].extensions).toEqual({ omp })
  expect(persisted()[0].agents).toEqual(['omp'])
  expect(persisted()[0].pi).toBeUndefined()
  expect(persisted()[1]).toMatchObject(suites[1])
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await page.getByLabel('PI', { exact: true }).check()
  await expect(piPaths).toHaveValue('')
  await expect(ompPaths).toHaveValue(omp.join('\n'))
})

