// Approved seams S1/S2/S3. P3's independent declaration below must be the
// actual authority, not a UI-only copy. A save that updates only memory (or a
// generated manifest) would disagree with both the disk literal and read-back.
test('P3 manages an unreferenced Suite through the main interface and authoritative file', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const definitions = path.join(path.dirname(server.configPath), 'meta-data', 'suites.json')
  const mcp = path.join(path.dirname(server.configPath), 'meta-data', 'mcp.json')
  fs.mkdirSync(path.dirname(mcp), { recursive: true })
  const catalogBytes = '{"mcpServers":{"catalog-search":{"command":"controlled-search","args":["--stdio"]}}}\n'
  fs.writeFileSync(mcp, catalogBytes)
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  const list = page.getByRole('region', { name: 'Suite 列表', exact: true })
  await expect(list).toContainText('尚未定义 Suite')
  await page.getByRole('button', { name: '创建 Suite', exact: true }).click()
  await page.getByLabel('Suite ID', { exact: true }).fill('review-tools')
  await page.getByLabel('Suite 名称', { exact: true }).fill('评审工具')
  await page.getByLabel('Skills（每行一个路径）', { exact: true }).fill('${roots.skills}/code-review\n../shared/research')
  await page.getByLabel('OMP Extensions（每行一个具体路径）', { exact: true }).fill('${roots.toolkit}/extensions/review')
  await page.getByLabel('Prompt templates（每行一个路径）', { exact: true }).fill('../prompts/review.md')
  await page.getByLabel('LSP 声明（JSON）', { exact: true }).fill('{"rust":{"command":"rust-analyzer","fileTypes":["rs"]}}')
  await page.getByLabel('catalog-search', { exact: true }).check()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  const expected = { id: 'review-tools', name: '评审工具', agents: ['omp'], skills: ['${roots.skills}/code-review', '../shared/research'], extensions: { omp: ['${roots.toolkit}/extensions/review'] }, prompts: ['../prompts/review.md'], lsp: { rust: { command: 'rust-analyzer', fileTypes: ['rs'] } }, mcp: ['catalog-search'] }
  await expect(list.getByRole('button', { name: '评审工具 · review-tools', exact: true })).toBeVisible()
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [expected] })
  expect(fs.readFileSync(mcp, 'utf8')).toBe(catalogBytes)
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await list.getByRole('button', { name: '评审工具 · review-tools', exact: true }).click()
  await expect(page.getByLabel('Suite ID', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Skills（每行一个路径）', { exact: true })).toHaveValue('${roots.skills}/code-review\n../shared/research')
  await expect(page.getByLabel('catalog-search', { exact: true })).toBeChecked()
  await page.getByLabel('Suite 名称', { exact: true }).fill('更新后的评审工具')
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(list.getByRole('button', { name: '更新后的评审工具 · review-tools', exact: true })).toBeVisible()
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [{ ...expected, name: '更新后的评审工具' }] })
  const response = await page.request.get(`${server.baseURL}/api/suites/review-tools`)
  expect(response.status()).toBe(200)
  expect(await response.json()).toEqual({ suite: { ...expected, name: '更新后的评审工具' } })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除 Suite', exact: true }).click()
  await expect(list).toContainText('尚未定义 Suite')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [] })
  expect(fs.readFileSync(mcp, 'utf8')).toBe(catalogBytes)
})

// P4: independent external bytes at an explicitly configured authority must win
// over default/cwd/generated lookalikes both before and after a real restart.
// A cached UI/database or a writer using cwd would fail the changed name/path.
test('P4 re-reads and restarts from the same externally maintained Suite authority', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const configDirectory = path.dirname(server.configPath)
  const authority = path.join(configDirectory, 'shared definitions with spaces')
  fs.mkdirSync(authority)
  const definitions = path.join(authority, 'user-suites.json')
  const external = '{"suites":[{"id":"external-tools","name":"外部独立定义","agents":["omp"],"skills":["../skills/independent"],"extensions":{},"prompts":[],"lsp":{},"mcp":[]}]}'
  fs.writeFileSync(definitions, external)
  const shadows = [path.join(server.cwd, 'meta-data'), path.join(configDirectory, 'meta-data'), path.join(configDirectory, 'generated')]
  for (const directory of shadows) {
    fs.mkdirSync(directory, { recursive: true })
    fs.writeFileSync(path.join(directory, 'suites.json'), '{"suites":[]}\n')
  }
  fs.appendFileSync(path.join(configDirectory, 'paths.toml'), `authority = '${authority}'\n`)
  fs.appendFileSync(server.configPath, "\n[suites]\ndefinition_file = '${roots.authority}/user-suites.json'\nmcp_file = 'shared definitions with spaces/central-mcp.json'\n")
  await server.restart()
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  await page.getByRole('button', { name: '外部独立定义 · external-tools', exact: true }).click()
  await expect(page.getByLabel('Skills（每行一个路径）', { exact: true })).toHaveValue('../skills/independent')
  expect(fs.readFileSync(definitions, 'utf8')).toBe(external)
  const revised = '{"suites":[{"id":"external-tools","name":"手工修改后的定义","agents":["omp"],"skills":["../skills/changed"],"extensions":{},"prompts":["../prompts/manual.md"],"lsp":{},"mcp":[]}]}'
  fs.writeFileSync(definitions, revised)
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(page.getByLabel('Suite 名称', { exact: true })).toHaveValue('手工修改后的定义')
  await expect(page.getByLabel('Prompt templates（每行一个路径）', { exact: true })).toHaveValue('../prompts/manual.md')
  const response = await page.request.get(`${server.baseURL}/api/suites/external-tools`)
  expect(response.status()).toBe(200)
  expect(await response.json()).toEqual({ suite: { id: 'external-tools', name: '手工修改后的定义', agents: ['omp'], skills: ['../skills/changed'], extensions: {}, prompts: ['../prompts/manual.md'], lsp: {}, mcp: [] } })
  await server.restart()
  await page.reload()
  await page.getByTestId('tab-suite').click()
  await page.getByRole('button', { name: '手工修改后的定义 · external-tools', exact: true }).click()
  await expect(page.getByLabel('Skills（每行一个路径）', { exact: true })).toHaveValue('../skills/changed')
  expect(fs.readFileSync(definitions, 'utf8')).toBe(revised)
  await page.getByLabel('Suite 名称', { exact: true }).fill('界面写回同一权威文件')
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [{ id: 'external-tools', name: '界面写回同一权威文件', agents: ['omp'], skills: ['../skills/changed'], extensions: {}, prompts: ['../prompts/manual.md'], lsp: {}, mcp: [] }] })
  for (const directory of shadows) expect(fs.readFileSync(path.join(directory, 'suites.json'), 'utf8')).toBe('{"suites":[]}\n')
  expect(fs.readdirSync(authority)).toEqual(['user-suites.json'])
})

test('shared extension choices keep independent IDs across entrypoint changes and retain invalid selections until cancelled', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const directory = path.dirname(server.configPath)
  const definitions = path.join(directory, 'meta-data', 'suites.json')
  const shared = '${roots.browser_extensions}/shared.ts'
  const relative = 'optional packages/relative.ts'
  const updated = 'optional packages/updated.ts'
  fs.mkdirSync(path.join(directory, 'optional packages'))
  for (const entry of ['extensions/shared.ts', relative, updated]) fs.writeFileSync(path.join(directory, entry), 'export default () => {}\n')
  const originalMetadata = fs.readFileSync(server.metadataFile, 'utf8')
  const catalog = (entry: string, agent = 'pi') => `\n[[extensions]]\nid = 'shared-pi-fixture'\nlabel = '共享浏览能力'\nagent = 'pi'\nkind = 'optional'\nentrypoint = '${shared}'\n\n[[extensions]]\nid = 'relative-pi-fixture'\nlabel = '相对路径能力'\nagent = '${agent}'\nkind = 'optional'\nentrypoint = '${entry}'\n`
  fs.writeFileSync(server.metadataFile, originalMetadata + catalog(relative))
  const suites = ['first', 'second'].map(id => ({ id, name: id, agents: ['pi'], skills: [], extensions: { pi: [shared, '../custom/pi-extra'] }, extensionOptions: { pi: ['shared-pi-fixture'] }, prompts: [], lsp: {}, mcp: [], pi: { codemode: 'on' } }))
  fs.mkdirSync(path.dirname(definitions), { recursive: true })
  fs.writeFileSync(definitions, JSON.stringify({ suites }))
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  const group = page.getByRole('group', { name: 'PI 共享可选扩展', exact: true })
  const choice = group.getByRole('checkbox', { name: /^共享浏览能力/ })
  const relativeChoice = group.getByRole('checkbox', { name: /^相对路径能力/ })
  const paths = page.getByLabel('PI Extensions（每行一个具体路径）', { exact: true })
  const persisted = () => JSON.parse(fs.readFileSync(definitions, 'utf8')).suites
  const save = async () => {
    await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  }
  await page.getByRole('button', { name: 'first · first', exact: true }).click()
  await expect(choice).toBeChecked()
  await paths.fill(`${shared}\n../custom/pi-extra\n${shared}`)
  await relativeChoice.check()
  await save()
  expect(persisted()[0].extensionOptions).toEqual({ pi: ['shared-pi-fixture', 'relative-pi-fixture'] })
  expect(persisted()[0].extensions).toEqual({ pi: [shared, '../custom/pi-extra'] })
  await choice.uncheck()
  await save()
  await expect(paths).toHaveValue(`${shared}\n../custom/pi-extra`)
  await page.getByRole('button', { name: 'second · second', exact: true }).click()
  await expect(choice).toBeChecked()
  await page.getByRole('button', { name: 'first · first', exact: true }).click()
  await expect(choice).not.toBeChecked()
  // A literal custom entry never implies a shared choice, even when it is identical.
  await expect(paths).toHaveValue(`${shared}\n../custom/pi-extra`)
  fs.writeFileSync(server.metadataFile, originalMetadata + catalog(updated))
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(relativeChoice).toBeChecked()
  await expect(group).toContainText(path.join(directory, updated))
  await save()
  expect(persisted()[0].extensionOptions).toEqual({ pi: ['relative-pi-fixture'] })
  expect(persisted()[0].extensions).toEqual({ pi: [shared, '../custom/pi-extra'] })
  // Changing the declared host must not silently move the selected ID.
  fs.writeFileSync(server.metadataFile, originalMetadata + catalog(updated, 'omp'))
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  const invalid = group.getByRole('checkbox', { name: /^relative-pi-fixture（失效/ })
  await expect(invalid).toBeChecked()
  await expect(relativeChoice).toHaveCount(0)
  fs.writeFileSync(server.metadataFile, originalMetadata)
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(invalid).toBeChecked()
  const beforeRejectedSave = fs.readFileSync(definitions, 'utf8')
  const rejected = page.waitForResponse(response => response.url().endsWith('/api/suites/first') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  expect((await rejected).status()).toBe(400)
  await expect(page.getByRole('alert')).toBeVisible()
  expect(fs.readFileSync(definitions, 'utf8')).toBe(beforeRejectedSave)
  await expect(invalid).toBeChecked()
  await page.setViewportSize({ width: 390, height: 844 })
  await invalid.focus()
  await page.keyboard.press('Space')
  await expect(invalid).toHaveCount(0)
  await save()
  expect(persisted()[0].extensionOptions ?? {}).toEqual({})
  expect(persisted()[0].extensions).toEqual({ pi: [shared, '../custom/pi-extra'] })
  expect(persisted()[1].extensionOptions).toEqual({ pi: ['shared-pi-fixture'] })
  await page.getByRole('button', { name: '创建 Suite', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /pi-web-access/ })).toHaveCount(0)
  await page.getByLabel('PI', { exact: true }).check()
  const web = page.getByRole('checkbox', { name: /pi-web-access/ })
  await web.focus()
  await page.keyboard.press('Space')
  await expect(web).toBeChecked()
  await page.getByLabel('Suite ID', { exact: true }).fill('new-pi')
  await page.getByLabel('Suite 名称', { exact: true }).fill('新 Pi Suite')
  await page.getByLabel('OMP', { exact: true }).uncheck()
  await save()
  expect(persisted().find((suite: { id: string }) => suite.id === 'new-pi').extensionOptions).toEqual({ pi: ['pi-web-access'] })
  await page.getByLabel('OMP', { exact: true }).check()
  await page.getByLabel('PI', { exact: true }).uncheck()
  await expect(web).toHaveCount(0)
  await save()
  expect(persisted().find((suite: { id: string }) => suite.id === 'new-pi').extensionOptions ?? {}).toEqual({})
})

// P25: closing only is explicitly on, never inheritance/off. Save and re-read
// the true authority after each transition; a UI-only toggle cannot satisfy it.
test('P25 saves explicit Pi on and only modes and hides Pi controls for OMP-only Suites', async ({ page }) => {
  server = await startServer({ separateCwd: true })
  const definitions = path.join(path.dirname(server.configPath), 'meta-data', 'suites.json')
  await page.goto(`${server.baseURL}?layout=expanded`)
  await page.getByTestId('tab-suite').click()
  await page.getByRole('button', { name: '创建 Suite', exact: true }).click()
  await page.getByLabel('Suite ID', { exact: true }).fill('mode-tools')
  await page.getByLabel('Suite 名称', { exact: true }).fill('模式工具')
  const piControls = page.getByRole('group', { name: 'Pi 配置', exact: true })
  await expect(piControls).toHaveCount(0)
  await page.getByLabel('PI', { exact: true }).check()
  await expect(piControls).toBeVisible()
  const only = page.getByLabel('Codemode only', { exact: true })
  await expect(only).not.toBeChecked()
  await expect(piControls).toContainText('关闭 only 表示明确的 on，不禁用，也不继承全局模式。')
  await only.check()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8'))).toEqual({ suites: [{ id: 'mode-tools', name: '模式工具', agents: ['omp', 'pi'], skills: [], extensions: {}, prompts: [], lsp: {}, mcp: [], pi: { codemode: 'only' } }] })
  await page.getByRole('button', { name: '关闭编辑', exact: true }).click()
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await page.getByRole('button', { name: '模式工具 · mode-tools', exact: true }).click()
  await expect(only).toBeChecked()
  await only.uncheck()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8')).suites[0].pi).toEqual({ codemode: 'on' })
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(only).not.toBeChecked()
  await page.getByLabel('OMP', { exact: true }).uncheck()
  await only.check()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8')).suites[0]).toEqual({ id: 'mode-tools', name: '模式工具', agents: ['pi'], skills: [], extensions: {}, prompts: [], lsp: {}, mcp: [], pi: { codemode: 'only' } })
  await page.getByLabel('OMP', { exact: true }).check()
  await page.getByLabel('PI', { exact: true }).uncheck()
  await expect(piControls).toHaveCount(0)
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8')).suites[0]).toEqual({ id: 'mode-tools', name: '模式工具', agents: ['omp'], skills: [], extensions: {}, prompts: [], lsp: {}, mcp: [] })
  await page.getByRole('button', { name: '重新读取 Suite', exact: true }).click()
  await expect(piControls).toHaveCount(0)
  await page.getByLabel('PI', { exact: true }).check()
  await expect(only).not.toBeChecked()
  await page.getByRole('button', { name: '保存 Suite', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Suite 已保存到权威文件。')
  expect(JSON.parse(fs.readFileSync(definitions, 'utf8')).suites[0].pi).toEqual({ codemode: 'on' })
})
